## Only `VariableOrigin` and its two enums are ported so far: the syntax tree
## needs them. The type errors come with the type checker.

import std/options
import ../[rust_enum, src_span]

type
  VariableSyntaxKind* = enum
    vsVariable
      ## A variable that can be ignored by prefixing with an underscore, `_name`
    vsLabelShorthand
      ## A variable from label shorthand syntax, which can be ignored with an underscore: `label: _`
    vsAssignmentPattern
      ## A variable from an assignment pattern, which can be ignored by removing `as name`.
    vsGenerated
      ## A variable generated by the compiler. This should never need to be ignored

  VariableSyntaxAssignmentPattern* = object of StructVariant
    name*: string ## Assignment name.
    location*: SrcSpan
      ## Location of assignment from the end of the pattern to the end of
      ## assignment itself, so it includes the `as` keyword.
      ## For example,
      ##
      ## ```gleam
      ## case x {
      ##   []     as wibble -> todo
      ##   //^^^^^^^^^^^^^^ This is location
      ##
      ##   [..] as wibble -> todo
      ##   //  ^^^^^^^^^^ This is location
      ## }
      ## ```

  VariableSyntax* = object
    ## The syntax used to define a variable. Used to determine how it can be ignored
    ## when unused.
    case kind*: VariableSyntaxKind
    of vsVariable:
      vVariable*: string
    of vsLabelShorthand:
      vLabelShorthand*: string
    of vsAssignmentPattern:
      vAssignmentPattern*: VariableSyntaxAssignmentPattern
    of vsGenerated:
      discard

  VariableDeclarationKind* = enum
    vdLetPattern
    vdUsePattern
    vdClausePattern
    vdFunctionParameter
    vdGenerated

  VariableDeclarationFunctionParameter* = object of StructVariant
    functionName*: Option[string]
      ## The name of the function defining the parameter. This will be None
      ## for parameters introduced by anoynmous functions: `fn(a) { a }`
    index*: int ## The index of the parameter in the function's parameter list.

  VariableDeclaration* = object
    ## The source of a variable, such as a `let` assignment, or function parameter.
    case kind*: VariableDeclarationKind
    of vdFunctionParameter:
      vFunctionParameter*: VariableDeclarationFunctionParameter
    of vdLetPattern, vdUsePattern, vdClausePattern, vdGenerated:
      discard

  VariableOrigin* = object
    syntax*: VariableSyntax
    declaration*: VariableDeclaration

func howToIgnore*(self: VariableOrigin): Option[string] =
  case self.syntax.kind
  of vsVariable:
    some("You can ignore it with an underscore: `_" & self.syntax.vVariable & "`.")
  of vsLabelShorthand:
    some(
      "You can ignore it with an underscore: `" & self.syntax.vLabelShorthand & ": _`."
    )
  of vsAssignmentPattern:
    some("You can safely remove it.")
  of vsGenerated:
    none(string)

func generated*(_: typedesc[VariableOrigin]): VariableOrigin =
  VariableOrigin(
    syntax: VariableSyntax(kind: vsGenerated),
    declaration: VariableDeclaration(kind: vdGenerated),
  )

func isGenerated*(self: VariableOrigin): bool =
  self.syntax.kind == vsGenerated

func isFunctionParameter*(self: VariableOrigin): bool =
  self.declaration.kind == vdFunctionParameter

func name*(self: VariableOrigin): Option[string] =
  ## Return name of variable. If it was generated, `None` is returned.
  case self.syntax.kind
  of vsVariable:
    some(self.syntax.vVariable)
  of vsLabelShorthand:
    some(self.syntax.vLabelShorthand)
  of vsAssignmentPattern:
    some(self.syntax.vAssignmentPattern.name)
  of vsGenerated:
    none(string)
