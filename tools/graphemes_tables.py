#!/usr/bin/env python3
"""Generates the Unicode tables of src/gleam_in_nim/graphemes.nim and their test data.

The Gleam compiler measures text in extended grapheme clusters with the Rust crate
unicode-segmentation (version 1.13.3 in the Cargo.lock of the pinned snapshot, Unicode 17.0.0).
To measure exactly as it does, the port takes its tables from that crate rather than from another
library or another Unicode version. Run this once per pin:

    curl -sSL https://static.crates.io/crates/unicode-segmentation/unicode-segmentation-1.13.3.crate | tar xz
    python3 tools/graphemes_tables.py unicode-segmentation-1.13.3

It writes src/gleam_in_nim/graphemes_tables.nim and tests/data/grapheme_clusters.txt.
unicode-segmentation is dual licensed MIT or Apache-2.0, copyright The Rust Project Developers.
"""
import os
import re
import sys

crate = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tables = open(os.path.join(crate, "src", "tables.rs"), encoding="utf8").read()
testdata = open(os.path.join(crate, "tests", "testdata", "mod.rs"), encoding="utf8").read()
version = re.search(r"UNICODE_VERSION: \(u64, u64, u64\) = \((\d+), (\d+), (\d+)\)", tables).groups()


def block(source, start):
    """The text of the Rust array literal that follows `start`."""
    begin = source.index(start)
    begin = source.index("&[", source.index("=", begin)) + 2
    return source[begin:source.index("];", begin)]


CHAR = r"'\\u\{([0-9a-f]+)\}'"
categories = [(int(lo, 16), int(hi, 16), cat) for lo, hi, cat in
              re.findall(CHAR + r",\s*" + CHAR + r",\s*GC_(\w+)\)", block(tables, "const grapheme_cat_table"))]
incb_extend = [(int(lo, 16), int(hi, 16)) for lo, hi in
               re.findall(r"\(" + CHAR + r",\s*" + CHAR + r"\)", block(tables, "const InCB_Extend_table"))]
linker_line = tables[tables.index("pub fn is_incb_linker"):]
linkers = [int(c, 16) for c in re.findall(CHAR, linker_line[:linker_line.index("}\n")], re.I)]
assert categories == sorted(categories) and incb_extend == sorted(incb_extend)
names = sorted({cat for _, _, cat in categories})

out = [
    "# Generated by tools/graphemes_tables.py from the Rust crate unicode-segmentation 1.13.3",
    "# (MIT or Apache-2.0, copyright The Rust Project Developers). Do not edit by hand.",
    "",
    "const unicodeVersion* = (%s, %s, %s)" % version,
    "",
    "type GraphemeCat* = enum",
    "  ## The Grapheme_Cluster_Break property of a character, with two additions the rules need:",
    "  ## Extended_Pictographic and Indic_Conjunct_Break=Consonant.",
    "  gcAny",
]
out += ["  gc" + name.replace("_", "") for name in names]
out += ["", "const graphemeCatTable*: array[%d, tuple[lo, hi: int32, cat: GraphemeCat]] = [" % len(categories)]
out += ["  (0x%X'i32, 0x%X'i32, gc%s)," % (lo, hi, cat.replace("_", "")) for lo, hi, cat in categories]
out += ["]", "", "const incbExtendTable*: array[%d, tuple[lo, hi: int32]] = [" % len(incb_extend)]
out += ["  (0x%X'i32, 0x%X'i32)," % pair for pair in incb_extend]
out += ["]", "", "const incbLinkers*: array[%d, int32] = [" % len(linkers)]
out += ["  " + ", ".join("0x%X'i32" % c for c in sorted(linkers))]
out += ["]", ""]
open(os.path.join(root, "src", "gleam_in_nim", "graphemes_tables.nim"), "w").write("\n".join(out))

# The test cases: a string and its extended grapheme clusters. TEST_SAME holds the strings that
# split the same way in legacy and extended mode, TEST_DIFF those that differ (extended first).
STRING = r'"((?:\\u\{[0-9a-f]+\})*)"'


def codepoints(literal):
    return " ".join(c.upper() for c in re.findall(r"\\u\{([0-9a-f]+)\}", literal))


cases = []
for text, clusters in re.findall(r"\(" + STRING + r",\s*&\[([^\]]*)\]\)", block(testdata, "pub const TEST_SAME")):
    cases.append((text, clusters))
for text, clusters in re.findall(r"\(" + STRING + r",\s*&\[([^\]]*)\],\s*&\[[^\]]*\]\)", block(testdata, "pub const TEST_DIFF")):
    cases.append((text, clusters))
lines = [
    "# Extended grapheme clusters: the test cases of the Rust crate unicode-segmentation 1.13.3",
    "# (Unicode %s.%s.%s), which derive from Unicode's GraphemeBreakTest.txt." % version,
    "# One case per line: code points in hexadecimal, clusters separated by a slash.",
    "# Generated by tools/graphemes_tables.py. Do not edit by hand.",
]
for text, clusters in cases:
    parts = [codepoints(part) for part in re.findall(STRING, clusters)]
    assert " ".join(parts) == codepoints(text), text
    lines.append(" / ".join(parts))
open(os.path.join(root, "tests", "data", "grapheme_clusters.txt"), "w").write("\n".join(lines) + "\n")
print("unicode %s.%s.%s:" % version, len(categories), "category ranges,", len(incb_extend), "InCB extend ranges,",
      len(linkers), "linkers,", len(cases), "test cases")
