// Writes src/gleam_in_nim/rust_debug_tables.nim: the code points from U+0080 up
// that Rust's `{:?}` writes as a `\u{..}` escape (not printable, or a grapheme
// extender). Asked of Rust itself, so the table is that of the toolchain that
// runs this, whose Unicode version is written in the output.
//
//   rustc -O tools/gen/rust_debug_tables.rs -o /tmp/gen && /tmp/gen > src/gleam_in_nim/rust_debug_tables.nim
fn main() {
    let mut ranges: Vec<(u32, u32)> = vec![];
    for cp in 0x80u32..=0x10FFFF {
        let Some(c) = char::from_u32(cp) else { continue };
        let as_char = format!("{:?}", c);
        let escaped = as_char.starts_with("'\\");
        // A string escapes exactly the same characters as a char, from U+0080 up.
        assert_eq!(format!("{:?}", c.to_string()).starts_with("\"\\"), escaped);
        if escaped {
            assert_eq!(as_char, format!("'\\u{{{:x}}}'", cp));
            match ranges.last_mut() {
                // The surrogates are not characters: a range may run over them.
                Some(last) if last.1 + 1 == cp || (last.1 == 0xD7FF && cp == 0xE000) => last.1 = cp,
                _ => ranges.push((cp, cp)),
            }
        }
    }
    let (major, minor, patch) = char::UNICODE_VERSION;
    println!("# Generated by tools/gen/rust_debug_tables.rs: do not edit.");
    println!("# SPDX-License-Identifier: Apache-2.0");
    println!("# SPDX-FileCopyrightText: 2026 The gleam-in-nim contributors");
    println!();
    println!("const rustDebugUnicodeVersion* = \"{major}.{minor}.{patch}\"");
    println!();
    println!("const rustDebugEscaped*: array[{}, tuple[lo, hi: int32]] = [", ranges.len());
    for chunk in ranges.chunks(4) {
        let row: Vec<String> = chunk.iter().map(|(a, b)| format!("(0x{a:X}'i32, 0x{b:X}'i32)")).collect();
        println!("  {},", row.join(", "));
    }
    println!("]");
}
