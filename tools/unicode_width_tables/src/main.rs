use unicode_width::UnicodeWidthChar;

fn main() {
    let (major, minor, patch) = unicode_width::UNICODE_VERSION;
    println!("# SPDX-License-Identifier: MIT OR Apache-2.0");
    println!("# Generated by tools/unicode_width_tables from the Rust crate unicode-width 0.2.2");
    println!("# (Unicode {major}.{minor}.{patch}). Do not edit.");
    println!();
    println!("## The code points whose width is not 1: `(first, last, width)`, sorted. A width of 0 is");
    println!("## also given to the code points for which the crate answers `None` (control characters).");
    println!("const widthRanges*: array[RANGES, tuple[first, last: int32, width: int8]] = [");
    let mut count = 0;
    let mut body = String::new();
    let mut start: Option<(u32, usize)> = None;
    for cp in 0..=0x110000u32 {
        let w = if cp == 0x110000 {
            1
        } else {
            match char::from_u32(cp) {
                Some(c) => c.width().unwrap_or(0),
                None => 1,
            }
        };
        match start {
            Some((s, sw)) if sw != w => {
                body.push_str(&format!("  (0x{:X}'i32, 0x{:X}'i32, {}'i8),\n", s, cp - 1, sw));
                count += 1;
                start = if w != 1 { Some((cp, w)) } else { None };
            }
            None if w != 1 => start = Some((cp, w)),
            _ => {}
        }
    }
    print!("{}", body);
    println!("]");
    eprintln!("{count} ranges");
}
